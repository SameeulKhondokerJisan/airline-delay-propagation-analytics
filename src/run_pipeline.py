"""End-to-end pipeline: Parquet staging -> warehouse -> rotations and propagation -> statistics -> risk model ->
figures -> Excel, Tableau and docs.

Usage:
    python -m src.run_pipeline                  # full run
    python -m src.run_pipeline --analysis-only  # skip Excel, Tableau and README rendering
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone

import numpy as np
import pandas as pd

from src import config, data, delays, figures, model


def records(df: pd.DataFrame) -> list[dict]:
    out = []
    for rec in df.to_dict(orient="records"):
        clean = {}
        for k, v in rec.items():
            if isinstance(v, (pd.Timestamp, datetime)):
                clean[k] = v.strftime("%Y-%m-%d")
            elif isinstance(v, (np.floating, float)):
                clean[k] = None if np.isnan(v) else float(v)
            elif isinstance(v, np.integer):
                clean[k] = int(v)
            elif isinstance(v, np.bool_):
                clean[k] = bool(v)
            else:
                clean[k] = v
        out.append(clean)
    return out


def write_quality_log(checks: pd.DataFrame, counts: dict) -> None:
    lines = ["# Data quality log", "",
             "Generated by `src/run_pipeline.py` from `sql/02_quality_checks.sql`. Hard rules stop the pipeline; "
             "soft rules are known features of the BTS file and are handled as described in `docs/methodology.md`.",
             "", "| Rule | Severity | Rows | Status |", "|---|---|---:|---|"]
    for r in checks.itertuples():
        status = "pass" if r.failures == 0 else ("FAIL" if r.severity == "hard" else "noted")
        lines.append(f"| {r.rule} | {r.severity} | {int(r.failures):,} | {status} |")
    lines += ["", "## Row counts", "", "| Table | Rows |", "|---|---:|"]
    lines += [f"| {k} | {v:,} |" for k, v in counts.items()]
    (config.ROOT / "docs" / "data_quality_log.md").write_text("\n".join(lines) + "\n")


def main(analysis_only: bool = False) -> dict:
    for folder in (config.FIGURES, config.TABLES, config.TABLEAU_DATA):
        folder.mkdir(parents=True, exist_ok=True)
    checks = data.build_warehouse()
    counts = data.row_counts()
    write_quality_log(checks, counts)
    print("warehouse built", counts, flush=True)

    tp = data.query("04_turn_profile.sql")
    buffers = data.query("05_buffer_scenarios.sql")
    carriers = data.query("06_carriers.sql")
    carrier_turns = data.query("07_carrier_turns.sql")
    airports = data.query("08_airports.sql")
    hourly = data.query("09_hourly.sql")
    daily = data.query("10_daily.sql")
    monthly = data.query("11_monthly_causes.sql")
    routes = data.query("12_routes.sql")
    shut_airports = data.query("13_shutdown_airports.sql")
    carrier_days = data.query("15_carrier_days.sql")
    check = data.query("16_propagation_check.sql").iloc[0]
    prop = data.query("17_propagation_totals.sql").iloc[0]
    min_turns = data.query("SELECT * FROM min_turn ORDER BY forced_turns DESC")

    sc = delays.carrier_scorecard(carriers, carrier_days)
    cause = delays.cause_summary(monthly)
    shut = delays.shutdown(daily)
    print("delay statistics done", flush=True)
    frame = data.query("14_model_frame.sql")
    risk = model.fit_and_score(frame)
    del frame
    print(f"risk model done (AUC {risk['metrics']['auc']:.3f})", flush=True)

    ops = daily.operated.sum()
    network = {"scheduled": int(daily.scheduled.sum()), "operated": int(ops), "cancelled": int(daily.cancelled.sum()),
               "cancel_rate": float(daily.cancelled.sum() / daily.scheduled.sum()),
               "on_time_rate": float(1 - daily.delayed15.sum() / ops),
               "arr_delay_minutes": float(daily.arr_delay_minutes.sum()),
               "arr_delay_min_per_flight": float(daily.arr_delay_minutes.sum() / ops),
               "carriers": int(len(carriers)), "carriers_full_window": int(sc.full_window.sum()),
               "airports": int(len(airports)), "days": int(len(daily)),
               "first_date": str(pd.to_datetime(daily.flight_date).min().date()),
               "last_date": str(pd.to_datetime(daily.flight_date).max().date())}
    h = hourly.set_index("dep_hour")
    hour_stats = {"dep_delay15_6am": float(h.loc[6, "dep_delay15_rate"]),
                  "dep_delay15_peak": float(h.loc[15:21, "dep_delay15_rate"].max()),
                  "peak_hour": int(h.loc[15:21, "dep_delay15_rate"].idxmax()),
                  "late_aircraft_share_6am": float(h.loc[6, "late_aircraft_share"]),
                  "late_aircraft_share_peak": float(h.loc[15:21, "late_aircraft_share"].max())}
    tpi = tp.set_index("sched_turn_bin")

    def share_at(lo, hi, col):
        s = tp[tp.sched_turn_bin.between(lo, hi)]
        return float(np.average(s[col], weights=s.turns))
    turn_stats = {"late_if_inbound_late_30_40": share_at(30, 40, "share_departs_late_if_inbound_late"),
                  "late_if_inbound_late_90_120": share_at(90, 120, "share_departs_late_if_inbound_late"),
                  "late_if_inbound_on_time_30_40": share_at(30, 40, "share_departs_late_if_inbound_on_time")}
    del tpi
    eff = shut["effects"]
    main_eff = eff[eff["sample"] == "Excluding Hurricane Milton week"]
    effd = {(r.metric, r.period): r for r in main_eff.itertuples()}
    effall = {(r.metric, r.period): r for r in eff[eff["sample"] == "All days"].itertuples()}
    means = shut["means"].set_index("period")
    sa = shut_airports.copy()
    sa["nas_change"] = sa.nas_min_per_dep_2025 - sa.nas_min_per_dep_2024
    sa["cancel_change"] = sa.cancel_rate_2025 - sa.cancel_rate_2024
    bufd = buffers.set_index(["carrier", "time_window", "threshold", "buffer"])
    total_prop = float(prop.propagated_minutes)

    tables = {"quality_checks": checks, "turn_profile": tp, "buffer_scenarios": buffers, "carrier_scorecard": sc,
              "carrier_turns": carrier_turns, "airports": airports, "hourly": hourly, "daily": daily,
              "monthly_causes": monthly, "routes_top50": routes, "shutdown_airports": sa, "min_turn": min_turns,
              "shutdown_effects": eff, "shutdown_period_means": shut["means"], "shutdown_weekly": shut["weekly"],
              "model_deciles": risk["deciles"], "model_calibration": risk["calibration"],
              "model_importance": risk["importance"]}
    for name, t in tables.items():
        t.to_csv(config.TABLES / f"{name}.csv", index=False)

    figs = [figures.monthly(monthly), figures.causes(monthly), figures.hourly(hourly), figures.turn_profile(tp, min_turns),
            figures.carriers(sc), figures.shutdown_weekly(shut["weekly"]), figures.airport_map(airports),
            figures.model_lift(risk["deciles"], risk["calibration"]), figures.buffer(buffers, total_prop)]

    results = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "settings": {"months": [f"{y}-{m:02d}" for y, m in config.MONTHS], "shutdown": [config.SHUTDOWN_START,
                                                                                        config.SHUTDOWN_END],
                     "flight_cuts": [config.CUTS_START, config.CUTS_END], "model_test_start": config.MODEL_TEST_START,
                     "cost_per_block_minute": config.COST_PER_BLOCK_MINUTE, "gate_components": config.GATE_COMPONENTS,
                     "passengers_per_departure": config.PASSENGERS_PER_DEPARTURE,
                     "passenger_value_of_time": config.PASSENGER_VALUE_OF_TIME},
        "row_counts": counts,
        "quality": {"hard_checks_passed": True, "rules": int(len(checks)),
                    "soft_findings": records(checks[(checks.severity == "soft") & (checks.failures > 0)])},
        "network": network,
        "causes": cause,
        "carriers": records(sc),
        "hourly": hour_stats,
        "propagation": {**{k: (float(v) if not isinstance(v, (int, np.integer)) else int(v)) for k, v in prop.items()},
                        "check": {k: float(v) for k, v in check.items()}, "turn_profile": turn_stats,
                        "min_turn": records(min_turns)},
        "carrier_turns": records(carrier_turns),
        "buffer": {"rows": records(buffers), "total_propagated_minutes": total_prop,
                   "all_60_15": records(bufd.loc[[("All", "All day", 60, 15)]].reset_index())[0],
                   "all_45_10": records(bufd.loc[[("All", "All day", 45, 10)]].reset_index())[0],
                   "pm_60_15": records(bufd.loc[[("All", "Departures from 15:00", 60, 15)]].reset_index())[0]},
        "shutdown": {"effects": records(eff), "means": records(shut["means"]),
                     "nas_before_cuts": float(effd[("nas_min_per_flight", "Shutdown, before flight cuts")].effect),
                     "nas_with_cuts": float(effd[("nas_min_per_flight", "Shutdown with flight cuts")].effect),
                     "cancel_with_cuts": float(effd[("cancel_rate", "Shutdown with flight cuts")].effect),
                     "main": {f"{m}|{p}": {"effect": r.effect, "ci_low": r.ci_low, "ci_high": r.ci_high, "p": r.p}
                              for (m, p), r in effd.items()},
                     "all_days": {f"{m}|{p}": {"effect": r.effect, "ci_low": r.ci_low, "ci_high": r.ci_high,
                                               "p": r.p} for (m, p), r in effall.items()},
                     "airports": records(sa.sort_values("nas_change", ascending=False).head(15))},
        "model": risk["metrics"] | {"importance": records(risk["importance"].head(10)),
                                    "deciles": records(risk["deciles"])},
        "routes_top10": records(routes.head(10)),
        "figures": figs,
    }
    config.RESULTS_JSON.write_text(json.dumps(results, indent=2, default=str))

    if not analysis_only:
        from src import excel_model, report, tableau_workbook
        results["tableau"] = tableau_workbook.build(airports, sc, hourly, monthly, tp, buffers, shut["weekly"],
                                                    carrier_turns)
        results["excel"] = excel_model.build(results, sc, buffers, carrier_turns)
        report.render(results)
        config.RESULTS_JSON.write_text(json.dumps(results, indent=2, default=str))
    print(f"Pipeline finished: {network['scheduled']:,} flights, on-time {network['on_time_rate']:.3f}, "
          f"propagated share of departure delay {float(prop.propagated_share_of_departure_delay):.3f}")
    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--analysis-only", action="store_true")
    main(analysis_only=parser.parse_args().analysis_only)
